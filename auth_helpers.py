import streamlit as st
import psycopg2
from psycopg2.extras import RealDictCursor

import hashlib
import hmac
import secrets as pysecrets


ROLE_OWNER = "OWNER"
ROLE_ADMIN = "ADMIN"
ROLE_EMPLOYEE = "EMPLOYEE"

ALLOWED_ROLES = (ROLE_OWNER, ROLE_ADMIN, ROLE_EMPLOYEE)


def get_db_connection():
    """Open a fresh PostgreSQL connection to Supabase."""
    cfg = st.secrets["postgres"]

    return psycopg2.connect(
        host=cfg["host"],
        port=int(cfg.get("port", 5432)),
        user=cfg["user"],
        password=cfg["password"],
        dbname=cfg.get("dbname", cfg.get("database", "postgres")),
        sslmode="require",
        connect_timeout=10,
    )


def password_hash(password, salt=None):
    salt = salt or pysecrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac(
        "sha256",
        password.encode("utf-8"),
        bytes.fromhex(salt),
        310000
    )
    return f"pbkdf2_sha256$310000${salt}${digest.hex()}"


def password_matches(password, stored):
    try:
        algorithm, iterations, salt, expected = stored.split("$", 3)

        if algorithm != "pbkdf2_sha256":
            return False

        actual = hashlib.pbkdf2_hmac(
            "sha256",
            password.encode("utf-8"),
            bytes.fromhex(salt),
            int(iterations)
        ).hex()

        return hmac.compare_digest(actual, expected)

    except (ValueError, TypeError):
        return False


def initialise_auth():
    """Create the account table and bootstrap the first Owner."""
    connection = get_db_connection()

    try:
        cursor = connection.cursor()

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS app_users (
                user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(80) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                role VARCHAR(10) NOT NULL
                    CHECK (role IN ('OWNER', 'ADMIN', 'EMPLOYEE')),
                is_active BOOLEAN NOT NULL DEFAULT TRUE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        connection.commit()

        cursor.execute(
            "SELECT COUNT(*) FROM app_users WHERE role = 'OWNER'"
        )
        owner_exists = cursor.fetchone()[0] > 0

        if not owner_exists:
            auth_cfg = st.secrets.get("auth", {})
            bootstrap_username = str(
                auth_cfg.get("owner_username", "")
            ).strip()
            bootstrap_password = str(
                auth_cfg.get("owner_password", "")
            )

            if not bootstrap_username or len(bootstrap_password) < 12:
                return (
                    False,
                    "No Owner account exists. Check the [auth] "
                    "settings in .streamlit/secrets.toml."
                )

            cursor.execute(
                """
                INSERT INTO app_users
                    (username, password_hash, role, is_active)
                VALUES (%s, %s, 'OWNER', TRUE)
                """,
                (
                    bootstrap_username,
                    password_hash(bootstrap_password),
                ),
            )
            connection.commit()

        return True, ""

    finally:
        connection.close()


def authenticate(username, password):
    connection = get_db_connection()

    try:
        cursor = connection.cursor(cursor_factory=RealDictCursor)

        cursor.execute(
            """
            SELECT user_id, username, password_hash, role, is_active
            FROM app_users
            WHERE username = %s
            """,
            (username.strip(),),
        )

        user = cursor.fetchone()

        if (
            user
            and user["is_active"]
            and password_matches(password, user["password_hash"])
        ):
            return {
                "user_id": user["user_id"],
                "username": user["username"],
                "role": user["role"],
            }

        return None

    finally:
        connection.close()


def require_role(*roles):
    """Check the signed-in user's session role."""
    user = st.session_state.get("user")
    return bool(user and user.get("role") in roles)